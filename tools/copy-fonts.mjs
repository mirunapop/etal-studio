// Copies the latin-subset woff2 files we use out of the @fontsource packages
// (installed in tools/node_modules) into assets/fonts/, and writes the @font-face CSS.
//   cd tools && npm install && npm run fonts
// Only the files listed below are copied. node_modules is never committed.
import { copyFileSync, mkdirSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', 'assets', 'fonts');
mkdirSync(out, { recursive: true });

const RANGE = 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD';

// [family, fontsource package, file stem, [[weight, style], ...]]
const core = [
  ['IBM Plex Sans', 'ibm-plex-sans', 'ibm-plex-sans', [[300,'normal'],[400,'normal'],[500,'normal'],[600,'normal'],[700,'normal']]],
  ['IBM Plex Mono', 'ibm-plex-mono', 'ibm-plex-mono', [[400,'normal'],[500,'normal']]],
  ['Source Serif 4', 'source-serif-4', 'source-serif-4', [[400,'normal'],[600,'normal'],[700,'normal'],[400,'italic'],[600,'italic']]],
];
const grotesk = [
  ['Space Grotesk', 'space-grotesk', 'space-grotesk', [[400,'normal'],[500,'normal'],[700,'normal']]],
];

function build(groups, title) {
  let css = `/* ${title}. Self-hosted, latin subset, from @fontsource (SIL OFL 1.1). Generated by tools/copy-fonts.mjs. */\n`;
  for (const [family, pkg, stem, faces] of groups) {
    for (const [weight, style] of faces) {
      const file = `${stem}-latin-${weight}-${style}.woff2`;
      const src = join(here, 'node_modules', '@fontsource', pkg, 'files', file);
      if (!existsSync(src)) throw new Error(`missing ${src}; run npm install in tools/`);
      copyFileSync(src, join(out, file));
      copyFileSync(join(here, 'node_modules', '@fontsource', pkg, 'LICENSE'), join(out, `LICENSE-${pkg}.txt`)); // OFL asks for the licence to travel with the fonts
      css += `@font-face{font-family:'${family}';font-style:${style};font-weight:${weight};font-display:swap;src:url(fonts/${file}) format('woff2');unicode-range:${RANGE}}\n`;
    }
  }
  return css;
}

writeFileSync(join(here, '..', 'assets', 'fonts.css'), build(core, 'IBM Plex Sans, IBM Plex Mono, Source Serif 4'));
writeFileSync(join(here, '..', 'assets', 'fonts-grotesk.css'), build(grotesk, 'Space Grotesk (Source Code specimen and its preview on the specimens page)'));
console.log('Wrote assets/fonts.css, assets/fonts-grotesk.css and woff2 files in assets/fonts/');
